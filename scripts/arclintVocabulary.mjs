// Keeps BWrite's copy of ArcLint's DDD vocabulary in step with the installed arclint.
//   node scripts/arclintVocabulary.mjs sync   rewrites the snapshots from arclint
//   node scripts/arclintVocabulary.mjs check  fails when a snapshot differs from arclint
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const arclint = (...args) => execFileSync("arclint", args, { cwd: root, encoding: "utf8" });

/** The concepts module the domain model imports: generated, so it always states arclint's own words. */
function conceptsModule() {
  const concepts = JSON.parse(arclint("domain", "explain", "--format", "json"));
  return `// Generated by scripts/arclintVocabulary.mjs from \`arclint domain explain --format json\`. Do not edit.
// Refresh with \`mise run vocab:sync\`; \`mise run vocab:check\` fails when it differs from the installed arclint.

/** One building block of ArcLint's Domain-Driven Design vocabulary, exactly as arclint explains it. */
export interface ArcLintConcept {
  type: string;
  title: string;
  meaning: string;
  questions: readonly string[];
  supplies: string;
  sources: readonly { readonly citation: string; readonly [field: string]: unknown }[];
}

export const ARCLINT_CONCEPTS: readonly ArcLintConcept[] = ${JSON.stringify(concepts, null, 2)};
`;
}

const SNAPSHOTS = [
  { file: "src/contexts/authoring/domain/arclint-concepts.ts", render: conceptsModule },
  { file: "tests/fixtures/arclint/domainSchema.json", render: () => arclint("domain", "schema") },
];

const mode = process.argv[2];
if (mode !== "sync" && mode !== "check") {
  console.error("usage: node scripts/arclintVocabulary.mjs sync|check");
  process.exit(2);
}

let stale = 0;
for (const { file, render } of SNAPSHOTS) {
  const live = render();
  const path = `${root}${file}`;
  if (mode === "sync") {
    writeFileSync(path, live);
    console.log(`wrote ${file}`);
  } else if (readFileSync(path, "utf8") !== live) {
    stale += 1;
    console.error(`${file} differs from the installed arclint; run the sync mode and review the change`);
  }
}
if (stale > 0) process.exit(1);
if (mode === "check") console.log("ArcLint vocabulary snapshots match the installed arclint.");
